#!/usr/bin/env node
/**
 * Register this checkout as a Cursor local plugin (idempotent).
 *
 * 1. Ensures dist/index.cjs exists (run `npm run build` first if missing).
 * 2. Syncs the plugin surface into ~/.cursor/plugins/local/open-delegate
 *    with an mcp.json that runs `node <absolute>/dist/index.cjs` — so Cursor
 *    does not call `npx -y @verbalize/open-delegate` (404 until the package
 *    is published on npm).
 * 3. Installs a user-level workspaceOpen hook that returns pluginPaths for
 *    that local plugin directory.
 *
 * The checkout's mcp.json stays the marketplace form (`npx -y @verbalize/…`).
 */
import {
	cpSync,
	existsSync,
	mkdirSync,
	readFileSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { homedir } from "node:os";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const DIST_ENTRY = join(ROOT, "dist", "index.cjs");
const CURSOR_DIR = join(homedir(), ".cursor");
const LOCAL_PLUGIN = join(CURSOR_DIR, "plugins", "local", "open-delegate");
const HOOKS_JSON = join(CURSOR_DIR, "hooks.json");
const HOOKS_DIR = join(CURSOR_DIR, "hooks");
const HOOK_SCRIPT = join(HOOKS_DIR, "open-delegate-plugin-paths.mjs");
const MARKER = "open-delegate-plugin-paths";

if (!existsSync(DIST_ENTRY)) {
	console.error(`Missing ${DIST_ENTRY}`);
	console.error("Run `npm run build` first, then re-run `npm run register:local`.");
	process.exit(1);
}

const distEntryPosix = DIST_ENTRY.replace(/\\/g, "/");
const localPluginPosix = LOCAL_PLUGIN.replace(/\\/g, "/");
const hookScriptPosix = HOOK_SCRIPT.replace(/\\/g, "/");
const hookCommand = `node ${hookScriptPosix}`;

/** Paths Cursor loads from a plugin install (not full src/). */
const SYNC_ITEMS = [
	".cursor-plugin",
	"skills",
	"rules",
	"assets",
	"docs",
	"dist",
	"README.md",
	"package.json",
	"LICENSE",
];

mkdirSync(LOCAL_PLUGIN, { recursive: true });
for (const item of SYNC_ITEMS) {
	const from = join(ROOT, item);
	const to = join(LOCAL_PLUGIN, item);
	if (!existsSync(from)) continue;
	if (existsSync(to)) rmSync(to, { recursive: true, force: true });
	cpSync(from, to, { recursive: true });
}

const localMcp = {
	mcpServers: {
		"open-delegate": {
			command: "node",
			args: [distEntryPosix],
		},
	},
};
writeFileSync(join(LOCAL_PLUGIN, "mcp.json"), `${JSON.stringify(localMcp, null, "\t")}\n`, "utf8");
console.log(`Synced plugin surface -> ${LOCAL_PLUGIN}`);
console.log(`Local mcp.json        -> node ${distEntryPosix}`);

const hookSource = `#!/usr/bin/env node
// Auto-generated by open-delegate scripts/register-local-plugin.mjs
// Returns pluginPaths so Cursor loads the synced local open-delegate plugin.
let input = "";
process.stdin.setEncoding("utf8");
process.stdin.on("data", (c) => { input += c; });
process.stdin.on("end", () => {
	try { JSON.parse(input || "{}"); } catch { /* ignore */ }
	process.stdout.write(JSON.stringify({ pluginPaths: [${JSON.stringify(localPluginPosix)}] }));
});
`;

mkdirSync(HOOKS_DIR, { recursive: true });
writeFileSync(HOOK_SCRIPT, hookSource, "utf8");

let hooks = { hooks: {} };
if (existsSync(HOOKS_JSON)) {
	try {
		hooks = JSON.parse(readFileSync(HOOKS_JSON, "utf8"));
	} catch (e) {
		console.error(`Failed to parse ${HOOKS_JSON}: ${e.message}`);
		process.exit(1);
	}
}
if (!hooks.hooks || typeof hooks.hooks !== "object") hooks.hooks = {};
if (!Array.isArray(hooks.hooks.workspaceOpen)) hooks.hooks.workspaceOpen = [];

const entries = hooks.hooks.workspaceOpen;
const idx = entries.findIndex(
	(e) =>
		typeof e === "object" &&
		e &&
		typeof e.command === "string" &&
		e.command.includes(MARKER),
);
if (idx >= 0) {
	entries[idx] = { command: hookCommand };
	writeFileSync(HOOKS_JSON, `${JSON.stringify(hooks, null, 2)}\n`, "utf8");
	console.log(`Updated workspaceOpen hook -> ${HOOKS_JSON}`);
} else {
	entries.push({ command: hookCommand });
	writeFileSync(HOOKS_JSON, `${JSON.stringify(hooks, null, 2)}\n`, "utf8");
	console.log(`Added workspaceOpen hook -> ${HOOKS_JSON}`);
}

console.log(`Hook script -> ${HOOK_SCRIPT}`);
console.log(`pluginPaths  -> ${LOCAL_PLUGIN}`);
console.log("");
console.log("Then: Cursor -> Developer: Reload Window");
console.log("Customize -> MCP Tools should list open-delegate with 6 tools.");
console.log("(Local MCP uses node + dist; marketplace mcp.json still uses npx once published.)");
